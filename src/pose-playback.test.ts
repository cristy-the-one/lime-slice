import assert from "node:assert/strict";
import { PosePlayback } from "./pose-playback.ts";
const p = new PosePlayback(4, 4);
assert.equal(p.frame(0), 0);
p.play(1000);
assert.equal(p.frame(1249), 0);
assert.equal(p.frame(1500), 2);
p.pause(1550);
assert.equal(p.frame(5000), 2);
p.play(5000);
assert.equal(p.frame(5250), 3);
assert.equal(p.frame(5500), 3);
assert.equal(p.playing, false);
assert.equal(p.seek(-1), 0);
assert.equal(p.seek(20), 3);
p.play(6000);
assert.equal(p.frame(6000), 0);
assert.throws(() => new PosePlayback(0, 12));
console.log("pose playback: play, pause, seek and replay passed");
