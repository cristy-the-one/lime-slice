export type { ModelPick, ModelSolid, ModelGhost, FacePointer, HandleDrag, ModelGrabHooks, EdgeKnobEvent, StressDraw, ModelView, SketchDraw, SketchViewPointer, SketchCameraCommand, SketchViewState } from "./model-view/types";

export function createModelView(canvas: HTMLCanvasElement): ModelView {
  const ctx = { canvas } as ViewCtx;
  installScene(ctx);
  installState(ctx);
  installMesh(ctx);
  installContext(ctx);
  installChrome(ctx);
  installGhost(ctx);
  installSplit(ctx);
  installFrame(ctx);
  installPicking(ctx);
  installEvents(ctx);
  installStress(ctx);
  installSketch(ctx);
  installHandles(ctx);
  installAspect(ctx);
  installLayout(ctx);
  installSnap(ctx);
  installGrab(ctx);
  ctx.mountGrabListeners();
  return buildApi(ctx);
}
