import { purgeLineWidth, purgeLineZ } from "./belt-purge.ts";

let failed = 0;
function eq(name: string, got: unknown, want: unknown): void {
  const a = JSON.stringify(got);
  const b = JSON.stringify(want);
  if (a === b) return;
  failed += 1;
  console.error(`FAIL ${name}\n  got  ${a}\n  want ${b}`);
}

const head = ["; generated by Lime Slice", "G21", "G28", "; belt: angle 45 axis Z dir +1", "; belt floor supports"];
const body = (lines: string[]) => [...head, ...lines, "M84", ""].join("\n");

// 1.75 mm filament: 25 mm of it over 250 mm and a 0.2 mm layer is 1.2026 mm wide.
eq("width from the filament", Math.round(purgeLineWidth(1.75, 0.2) * 10000) / 10000, 1.2026);
eq("unknown filament is 1.2", purgeLineWidth(undefined, 0.2), 1.2);
eq("unknown layer height is 1.2", purgeLineWidth(1.75, 0), 1.2);

// Supports touch the belt at 0.283; the part's outer wall first touches at 1.414.
const supportFirst = body([
  ";LAYER:0 Z:0.283 H:0.200 ",
  "G1 Z0.283 F7200",
  ";TYPE:SUPPORT",
  "G1 X10.000 Y0.100 F18000",
  "G1 X11.000 Y0.199 E0.01 F1800",
  ";TYPE:OUTER",
  "G1 X20.000 Y3.000 E0.02 F1800",
  ";LAYER:5 Z:1.414 H:0.200 ",
  "G1 Z1.414 F7200",
  ";TYPE:SUPPORT-INTERFACE",
  "G1 X11.000 Y0.150 E0.03 F1800",
  ";TYPE:OUTER",
  "G1 X30.000 Y0.200 E0.04 F1800",
  ";LAYER:6 Z:1.614 H:0.200 ",
  ";TYPE:OUTER",
  "G1 X30.000 Y0.150 E0.05 F1800",
]);
eq("a support first touching earlier is not the part: the wall decides", purgeLineZ(supportFirst, 1.75), 0.813);
eq("filament unknown uses a 1.2 line", purgeLineZ(supportFirst), 0.814);

const partOnly = body([
  ";LAYER:0 Z:0.283 H:0.200 ",
  "G1 Z0.283 F7200",
  ";TYPE:SKIRT",
  "G1 X1.000 Y0.100 F18000",
  "G1 X2.000 Y0.250 E0.01 F1800",
  ";TYPE:OUTER",
  "G1 X20.000 Y0.100 E0.02 F1800",
]);
eq("a part touching in the first layer", purgeLineZ(partOnly, 1.75), -0.318);

const supportsOnly = body([
  ";LAYER:0 Z:0.283 H:0.200 ",
  ";TYPE:SUPPORT",
  "G1 X11.000 Y0.150 E0.03 F1800",
  ";LAYER:2 Z:0.683 H:0.200 ",
  ";TYPE:SUPPORT",
  "G1 X11.000 Y0.150 E0.03 F1800",
]);
eq("only supports touch the belt: the smallest of them", purgeLineZ(supportsOnly, 1.75), -0.318);

const nothingTouches = body([";LAYER:0 Z:0.283 H:0.200 ", ";TYPE:OUTER", "G1 X20.000 Y4.000 E0.02 F1800"]);
eq("nothing touches: the first layer's position", purgeLineZ(nothingTouches, 1.75), -0.318);

eq("no body at all is zero", purgeLineZ(head.join("\n") + "\n", 1.75), 0);
eq("no belt comment is zero", purgeLineZ(";LAYER:0 Z:0.283 H:0.200 \n;TYPE:OUTER\nG1 X1 Y0.1 E1\n", 1.75), 0);
eq("a belt that is not Z is zero", purgeLineZ(supportFirst.replace("axis Z", "axis Y"), 1.75), 0);
eq("a belt running the other way is zero", purgeLineZ(supportFirst.replace("dir +1", "dir -1"), 1.75), 0);
eq("travel moves do not count", purgeLineZ(body([";LAYER:0 Z:0.283 H:0.200 ", ";TYPE:OUTER", "G1 X1.000 Y0.100 F18000", ";LAYER:3 Z:0.883 H:0.200 ", ";TYPE:OUTER", "G1 X2.000 Y0.100 E0.1 F1800"]), 1.75), 0.282);

if (failed > 0) throw new Error(`${failed} failed`);
console.log("belt-purge: ok");
