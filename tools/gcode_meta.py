"""Give an exported Lime Slice G-code file the timing metadata printers read.

usage: python tools/gcode_meta.py [--out OUT | --in-place] [--version 1.0.0] file.gcode

Moonraker (Mainsail, Fluidd) and Prusa firmware only show a slicer's estimate when
they recognise the file. This rewrites a Lime Slice file the way Export writes it:

- the first line becomes `; generated by Lime Slice <version> on <date> at <time>`,
  the pattern Moonraker identifies slicers by (date and time of the file);
- `M73 P<percent> R<minutes left>` after each `;LAYER:` line where the percent
  changes, and `M73 P100 R0` before the end G-code;
- PrusaSlicer-style totals at the end of the file: estimated printing time,
  filament used [mm] and [g], total layers count, layer_height, nozzle_diameter.

The file only holds the total time (`; TIME:` in the footer), so each layer's
share comes from replaying its moves (a trapezoid per move at the acceleration
in force, junction speeds by Klipper's junction deviation), scaled so the layers
add up to that total. Running it again on its output gives the same file.
"""

import argparse
import datetime
import math
import os
import re
import sys

WORD = re.compile(r"([A-Z])(-?\d*\.?\d+)")
FOOTER = re.compile(r";\s*TIME:([\d.]+)s\s+FILAMENT_MM:([\d.]+)\s+FILAMENT_G:([\d.]+)")
OLD_HEADER = re.compile(r"; generated by Lime Slice\b(?!.* on \d{4}-\d{2}-\d{2} at )")
OURS = ("; estimated printing time", "; filament used [", "; total layers count", "; layer_height =", "; nozzle_diameter =")
END_MARKS = ("PRINT_END", "M106 S0")


def junction_speed(d0, d1, v, a, jd):
    if d0 is None:
        return 0.0
    cos = -(d0[0] * d1[0] + d0[1] * d1[1] + d0[2] * d1[2])
    cos = max(-0.999999, min(0.999999, cos))
    sin_half = math.sqrt((1 - cos) / 2)
    if sin_half > 0.999:
        return v
    return min(v, math.sqrt(a * jd * sin_half / (1 - sin_half)))


def trapezoid(length, v, a, v0, v1):
    v0, v1 = min(v0, v), min(v1, v)
    d_acc = (v * v - v0 * v0) / (2 * a)
    d_dec = (v * v - v1 * v1) / (2 * a)
    if d_acc + d_dec <= length:
        return (v - v0) / a + (v - v1) / a + (length - d_acc - d_dec) / v
    peak = math.sqrt(max(0.0, (2 * a * length + v0 * v0 + v1 * v1) / 2))
    return max(0.0, (peak - v0) / a) + max(0.0, (peak - v1) / a)


def is_ours(line):
    return line.startswith("M73 ") or line.startswith(OURS)


def survey(path, jd=0.02):
    """Modelled seconds per layer, plus what the header and footer say."""
    seconds = []
    info = {"layer_height": None, "nozzle": None, "total": None, "mm": None, "g": None}
    pos = [0.0, 0.0, 0.0]
    feed, accel = 1800.0, 1500.0
    pending = None  # (layer, length, v, a, direction, v_in)
    with open(path, encoding="utf-8", errors="replace") as fh:
        for line in fh:
            if line.startswith(";"):
                if line.startswith(";LAYER:"):
                    seconds.append(0.0)
                elif line.startswith("; layer_height:"):
                    info["layer_height"] = float(line.split(":", 1)[1].split()[0])
                elif m := re.match(r"; bed .* nozzle ([\d.]+) mm", line):
                    info["nozzle"] = float(m.group(1))
                elif m := FOOTER.match(line):
                    info["total"], info["mm"], info["g"] = (float(x) for x in m.groups())
                continue
            code = line.split(";", 1)[0].split()
            if not code:
                continue
            cmd = code[0].upper()
            if cmd == "M204":
                words = dict((k, float(v)) for k, v in WORD.findall(" ".join(code[1:]).upper()))
                accel = words.get("S", words.get("P", accel))
            elif cmd == "G92":
                words = dict((k, float(v)) for k, v in WORD.findall(" ".join(code[1:]).upper()))
                for i, ax in enumerate("XYZ"):
                    if ax in words:
                        pos[i] = words[ax]
            elif cmd in ("G0", "G1", "G2", "G3"):
                words = dict((k, float(v)) for k, v in WORD.findall(" ".join(code[1:]).upper()))
                if "F" in words:
                    feed = words["F"]
                target = [words.get(ax, pos[i]) for i, ax in enumerate("XYZ")]
                delta = [target[i] - pos[i] for i in range(3)]
                length = math.sqrt(sum(c * c for c in delta))
                pos = target
                if length < 1e-9:
                    continue
                d = [c / length for c in delta]
                v = feed / 60
                v_in = 0.0
                if pending:
                    layer, plen, pv, pa, pd, pin = pending
                    v_in = junction_speed(pd, d, pv, pa, jd)
                    if layer >= 0:
                        seconds[layer] += trapezoid(plen, pv, pa, pin, v_in)
                pending = (len(seconds) - 1, length, v, accel, d, v_in)
    if pending and pending[0] >= 0:
        layer, plen, pv, pa, _, pin = pending
        seconds[layer] += trapezoid(plen, pv, pa, pin, 0.0)
    return seconds, info


def hms(total):
    total = round(total)
    d, rest = divmod(total, 86400)
    h, rest = divmod(rest, 3600)
    m, s = divmod(rest, 60)
    return (f"{d}d " if d else "") + f"{h}h {m}m {s}s"


def rewrite(src, dst, version, stamp):
    seconds, info = survey(src)
    if info["total"] is None:
        sys.exit(f"{src}: no '; TIME:...s FILAMENT_MM:... FILAMENT_G:...' footer, so this is not a Lime Slice export")
    if not seconds:
        sys.exit(f"{src}: no ;LAYER: lines")
    modelled = sum(seconds) or 1.0
    scale = info["total"] / modelled
    starts = []  # estimated seconds done when each layer starts
    done = 0.0
    for s in seconds:
        starts.append(done)
        done += s * scale
    total = info["total"]

    def m73(done_s):
        percent = min(100, int(100 * done_s / total))
        left = max(0, math.ceil((total - done_s) / 60))
        return percent, f"M73 P{percent} R{left}"

    with open(src, encoding="utf-8", errors="replace", newline="") as fh:
        lines = fh.readlines()
    eol = "\r\n" if lines and lines[0].endswith("\r\n") else "\n"
    # The end G-code starts at the last PRINT_END, or at the cooldown when there is none.
    end_at = None
    for mark in END_MARKS:
        for i in range(len(lines) - 1, -1, -1):
            if lines[i].startswith(mark):
                end_at = i
                break
        if end_at is not None:
            break
    tail_at = len(lines)
    if lines and lines[-1].rstrip("\r\n") == "M84":
        tail_at = len(lines) - 1
    totals = [
        f"; estimated printing time (normal mode) = {hms(total)}",
        f"; filament used [mm] = {info['mm']:.2f}",
        f"; filament used [g] = {info['g']:.2f}",
        f"; total layers count = {len(seconds)}",
    ]
    if info["layer_height"] is not None:
        totals.append(f"; layer_height = {info['layer_height']:g}")
    if info["nozzle"] is not None:
        totals.append(f"; nozzle_diameter = {info['nozzle']:g}")

    tmp = dst + ".tmp"
    layer = -1
    last_percent = None
    with open(tmp, "w", encoding="utf-8", newline="") as out:
        for i, line in enumerate(lines):
            if i == tail_at:
                out.writelines(t + eol for t in totals)
            if i == end_at:
                out.write("M73 P100 R0" + eol)
            if is_ours(line):
                continue
            if i == 0 and OLD_HEADER.match(line):
                out.write(f"; generated by Lime Slice {version} on {stamp:%Y-%m-%d} at {stamp:%H:%M:%S}{eol}")
                continue
            out.write(line)
            if line.startswith(";LAYER:"):
                layer += 1
                percent, text = m73(starts[layer])
                if percent != last_percent:
                    out.write(text + eol)
                    last_percent = percent
        if tail_at == len(lines):
            out.writelines(t + eol for t in totals)
    os.replace(tmp, dst)
    return len(seconds), total, scale


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    ap.add_argument("file")
    where = ap.add_mutually_exclusive_group()
    where.add_argument("--out", help="output file (default: <name>-meta.gcode next to the input)")
    where.add_argument("--in-place", action="store_true", help="replace the input file")
    ap.add_argument("--version", default="1.0.0", help="Lime Slice version written in the header")
    args = ap.parse_args()
    src = args.file
    dst = src if args.in_place else args.out or re.sub(r"(\.gcode)?$", "-meta.gcode", src, count=1, flags=re.I)
    stamp = datetime.datetime.fromtimestamp(os.path.getmtime(src))
    layers, total, scale = rewrite(src, dst, args.version, stamp)
    print(f"{dst}: {layers} layers, {hms(total)} estimated; layer times modelled x{scale:.3f} to match the file's total")


if __name__ == "__main__":
    main()
