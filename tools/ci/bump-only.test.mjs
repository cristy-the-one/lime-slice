// Run: node tools/ci/bump-only.test.mjs (listed in tools/unit-tests.txt).
// Each case commits a small fixture repo, applies a change, and classifies the real `git diff -U0` of it.
import { execFileSync } from "node:child_process";
import { mkdtempSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import {
  checkConsistency,
  classifyDiff,
  packageName,
  workspaceMembers,
} from "./bump-only.mjs";

let failed = 0;
function eq(name, actual, expected) {
  if (actual === expected) return;
  failed += 1;
  console.error(`FAIL ${name}: got ${actual}, expected ${expected}`);
}

const CRATES = ["crates/a", "crates/b"];

function fixture(v) {
  const lockPkg = (name, ver, source) =>
    `[[package]]\nname = "${name}"\nversion = "${ver}"\n${source ? `source = "registry+https://github.com/rust-lang/crates.io-index"\n` : ""}dependencies = [\n]\n`;
  return {
    "package.json": JSON.stringify(
      { name: "lime-slice", version: v, dependencies: { dep: "^1.0.0" } },
      null,
      2,
    ) + "\n",
    "package-lock.json": JSON.stringify(
      {
        name: "lime-slice",
        version: v,
        lockfileVersion: 3,
        packages: {
          "": { name: "lime-slice", version: v, dependencies: { dep: "^1.0.0" } },
          "node_modules/dep": { version: "1.0.0", resolved: "x" },
        },
      },
      null,
      2,
    ) + "\n",
    "src-tauri/tauri.conf.json": JSON.stringify({ productName: "Lime Slice", version: v, bundle: { active: true } }, null, 2) + "\n",
    "Cargo.toml": `[workspace]\nresolver = "2"\nmembers = [\n    "crates/a",\n    "crates/b",\n]\n\n[workspace.package]\nversion = "${v}"\nedition = "2021"\n\n[profile.release]\nlto = true\n`,
    "crates/a/Cargo.toml": `[package]\nname = "crate-a"\nversion.workspace = true\n\n[dependencies]\nserde = { version = "1" }\n`,
    "crates/b/Cargo.toml": `[package]\nname = "crate-b"\nversion.workspace = true\n`,
    "Cargo.lock": `# This file is automatically @generated by Cargo.\nversion = 4\n\n${lockPkg("crate-a", v)}\n${lockPkg("crate-b", v)}\n${lockPkg("serde", "1.0.0", true)}`,
    "README.md": `# Lime Slice\n\nLime Slice ${v} is a slicer. Version 1.${v.split(".")[1]}0.0 of a dependency stays.\n\nA manual run creates the draft (${v}). Draft releases through v${prev(v)} are already on the repository.\n`,
    "docs/note.md": "A note.\n",
    "src/main.ts": "export const x = 1;\n",
  };
}

function prev(v) {
  const [a, b, c] = v.split(".").map(Number);
  return c > 0 ? `${a}.${b}.${c - 1}` : `${a}.${b - 1}.0`;
}

// The bump: every version line from OLD to NEW, README sentence included.
function bump(files, from, to) {
  const out = { ...files };
  const swap = (s) => s.split(`"${from}"`).join(`"${to}"`);
  for (const p of ["package.json", "package-lock.json", "src-tauri/tauri.conf.json", "Cargo.toml"]) out[p] = swap(out[p]);
  // Cargo.lock: only the workspace crates, not serde
  out["Cargo.lock"] = out["Cargo.lock"].replace(/(name = "crate-[ab]"\nversion = ")[^"]+/g, `$1${to}`);
  out["README.md"] = out["README.md"]
    .replace(`Lime Slice ${from} is`, `Lime Slice ${to} is`)
    .replace(`(${from})`, `(${to})`)
    .replace(`through v${prev(from)}`, `through v${from}`);
  return out;
}

function run(base, change) {
  const dir = mkdtempSync(join(tmpdir(), "bump-only-"));
  const git = (...a) => execFileSync("git", ["-C", dir, ...a], { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
  const write = (files) => {
    for (const [p, c] of Object.entries(files)) {
      mkdirSync(dirname(join(dir, p)), { recursive: true });
      writeFileSync(join(dir, p), c);
    }
  };
  try {
    git("init", "-q");
    git("config", "user.email", "t@example.com");
    git("config", "user.name", "t");
    git("config", "core.autocrlf", "false");
    write(base);
    git("add", "-A");
    git("commit", "-q", "-m", "base");
    write(change(base));
    git("add", "-A");
    git("commit", "-q", "--allow-empty", "-m", "change");
    const diff = git("diff", "-U0", "--no-color", "--no-renames", "HEAD~1...HEAD");
    const show = (rev) => (p) => git("show", `${rev}:${p}`);
    const names = workspaceMembers(show("HEAD")("Cargo.toml")).map((d) => packageName(show("HEAD")(`${d}/Cargo.toml`)));
    return classifyDiff(diff, {
      read: (which, p) => {
        try {
          return show(which === "old" ? "HEAD~1" : "HEAD")(p);
        } catch {
          return "";
        }
      },
      workspaceNames: names,
    });
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

const OLD = "5.2.2";
const NEW = "5.3.0";
const base = fixture(OLD);
const case_ = (name, expected, change) => eq(name, run(base, change).bump, expected);

case_("a real bump is a bump", true, (f) => bump(f, OLD, NEW));
eq("bump reports the pair", `${run(base, (f) => bump(f, OLD, NEW)).from} ${run(base, (f) => bump(f, OLD, NEW)).to}`, `${OLD} ${NEW}`);
case_("bump without a README edit", true, (f) => {
  const o = bump(f, OLD, NEW);
  o["README.md"] = f["README.md"];
  return o;
});
case_("bump with docs alongside", true, (f) => ({ ...bump(f, OLD, NEW), "docs/note.md": "A note, edited.\n", "docs/new.md": "x\n" }));
case_("bump with a skills markdown file", true, (f) => ({ ...bump(f, OLD, NEW), ".claude/skills/release/SKILL.md": "x\n" }));
case_("bump plus a code change", false, (f) => ({ ...bump(f, OLD, NEW), "src/main.ts": "export const x = 2;\n" }));
case_("bump plus a new code file", false, (f) => ({ ...bump(f, OLD, NEW), "src/new.ts": "x\n" }));
case_("bump plus a workflow change", false, (f) => ({ ...bump(f, OLD, NEW), ".github/workflows/ci.yml": "x\n" }));
case_("code change only", false, (f) => ({ ...f, "src/main.ts": "export const x = 2;\n" }));
case_("docs only is not a bump", false, (f) => ({ ...f, "docs/note.md": "Edited.\n" }));
case_("no change is not a bump", false, (f) => f);

case_("a dependency version in package-lock", false, (f) => ({
  ...bump(f, OLD, NEW),
  "package-lock.json": bump(f, OLD, NEW)["package-lock.json"].replace('"version": "1.0.0"', '"version": "1.0.1"'),
}));
case_("a dependency bump alone in package-lock", false, (f) => ({
  ...f,
  "package-lock.json": f["package-lock.json"].replace('"version": "1.0.0"', '"version": "2.0.0"'),
}));
case_("a registry crate version in Cargo.lock", false, (f) => ({
  ...bump(f, OLD, NEW),
  "Cargo.lock": bump(f, OLD, NEW)["Cargo.lock"].replace('name = "serde"\nversion = "1.0.0"', 'name = "serde"\nversion = "1.0.1"'),
}));
case_("a registry crate alone in Cargo.lock", false, (f) => ({
  ...f,
  "Cargo.lock": f["Cargo.lock"].replace('name = "serde"\nversion = "1.0.0"', 'name = "serde"\nversion = "1.0.1"'),
}));
case_("Cargo.toml edition changed with the bump", false, (f) => ({
  ...bump(f, OLD, NEW),
  "Cargo.toml": bump(f, OLD, NEW)["Cargo.toml"].replace('edition = "2021"', 'edition = "2024"'),
}));
case_("a dependency version in a crate manifest", false, (f) => ({
  ...bump(f, OLD, NEW),
  "crates/a/Cargo.toml": f["crates/a/Cargo.toml"].replace('version = "1"', 'version = "2"'),
}));
case_("tauri.conf nested version", false, (f) => ({
  ...bump(f, OLD, NEW),
  "src-tauri/tauri.conf.json": bump(f, OLD, NEW)["src-tauri/tauri.conf.json"].replace('"active": true', '"active": false'),
}));

// Mismatched versions.
case_("a workspace crate left behind in Cargo.lock", false, (f) => {
  const o = bump(f, OLD, NEW);
  o["Cargo.lock"] = o["Cargo.lock"].replace(`name = "crate-b"\nversion = "${NEW}"`, `name = "crate-b"\nversion = "${OLD}"`);
  return o;
});
case_("package.json moved to a different version than the rest", false, (f) => {
  const o = bump(f, OLD, NEW);
  o["package.json"] = o["package.json"].replace(NEW, "5.4.0");
  return o;
});
case_("Cargo.toml not bumped", false, (f) => {
  const o = bump(f, OLD, NEW);
  o["Cargo.toml"] = f["Cargo.toml"];
  return o;
});
case_("packages[''] not bumped", false, (f) => {
  const o = bump(f, OLD, NEW);
  o["package-lock.json"] = f["package-lock.json"].replace(`"version": "${OLD}",\n  "lockfileVersion"`, `"version": "${NEW}",\n  "lockfileVersion"`);
  return o;
});

// README.
case_("README with an extra edit", false, (f) => {
  const o = bump(f, OLD, NEW);
  o["README.md"] = o["README.md"].replace("is a slicer", "is a fast slicer");
  return o;
});
case_("README with an extra line", false, (f) => {
  const o = bump(f, OLD, NEW);
  o["README.md"] += "More text.\n";
  return o;
});
case_("README edit alone, no version lines", false, (f) => ({ ...f, "README.md": f["README.md"].replace("is a slicer", "is a fast slicer") }));
case_("README says an unrelated version", false, (f) => {
  const o = bump(f, OLD, NEW);
  o["README.md"] = o["README.md"].replace("Version 1.20.0", "Version 1.30.0");
  return o;
});

// Consistency check alone.
{
  const ok = fixture(NEW);
  const names = ["crate-a", "crate-b"];
  const input = (o) => ({
    packageJson: o["package.json"],
    packageLock: o["package-lock.json"],
    tauriConf: o["src-tauri/tauri.conf.json"],
    cargoToml: o["Cargo.toml"],
    cargoLock: o["Cargo.lock"],
    workspaceNames: names,
  });
  eq("consistent versions", checkConsistency(input(ok)).length, 0);
  const stale = { ...ok, "Cargo.lock": ok["Cargo.lock"].replace(`name = "crate-a"\nversion = "${NEW}"`, `name = "crate-a"\nversion = "${OLD}"`) };
  eq("stale lock is reported", checkConsistency(input(stale)).length, 1);
  const missing = { ...ok, "Cargo.lock": ok["Cargo.lock"].replace(/\[\[package\]\]\nname = "crate-b"[^]*?\n\n/, "") };
  eq("missing workspace crate in the lock", checkConsistency(input(missing)).length > 0, true);
  eq("expected version is enforced", checkConsistency(input(ok), "9.9.9").length > 0, true);
}

if (failed > 0) {
  console.error(`${failed} bump-only test(s) failed`);
  process.exit(1);
}
console.log("bump-only: all tests passed");
