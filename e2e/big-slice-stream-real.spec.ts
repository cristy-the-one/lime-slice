import { readFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { expect, test, type Page } from "@playwright/test";
import { autoSliceOff } from "./auto-slice";
import { printerGcode } from "../src/print-file";

/**
 * A long part's slice reply comes in parts and its G-code is written by the engine, not held by the page.
 *   lime-slice serve --port 43218 --cache-dir <dir>
 *   LIME_EDIT_API=http://127.0.0.1:43218 npx playwright test big-slice-stream-real
 */
const api = process.env.LIME_EDIT_API;

test.skip(!api, "set LIME_EDIT_API to a running lime-slice serve");
test.setTimeout(180_000);

/** Three stacked boxes, `top` mm wide at the top: walls, skin, and infill on every layer. */
function stepsStl(top: number): string {
  const out = ["solid steps"];
  const boxes = [[0, 30, 0, 4], [5, 25, 4, 8], [15 - top / 2, 15 + top / 2, 8, 14]];
  for (const [lo, hi, z0, z1] of boxes) {
    const v = (x: number, y: number, z: number) => `vertex ${x} ${y} ${z}`;
    const a = [lo!, lo!, z0!];
    const b = [hi!, hi!, z1!];
    const p = (i: number) => [i & 1 ? b[0]! : a[0]!, i & 2 ? b[1]! : a[1]!, i & 4 ? b[2]! : a[2]!] as const;
    const quads = [[0, 2, 3, 1], [4, 5, 7, 6], [0, 1, 5, 4], [2, 6, 7, 3], [0, 4, 6, 2], [1, 3, 7, 5]];
    for (const q of quads) {
      for (const tri of [[q[0]!, q[1]!, q[2]!], [q[0]!, q[2]!, q[3]!]]) {
        out.push("facet normal 0 0 0", "outer loop", ...tri.map((i) => v(...p(i))), "endloop", "endfacet");
      }
    }
  }
  out.push("endsolid steps");
  return out.join("\n");
}

const sha = (data: string | Uint8Array) => createHash("sha256").update(data).digest("hex");

async function proxy(page: Page) {
  const urls: string[] = [];
  await page.route("http://127.0.0.1:43118/**", async (route) => {
    const url = route.request().url().replace("http://127.0.0.1:43118", api!);
    urls.push(url.slice(api!.length));
    await route.fulfill({ response: await route.fetch({ url, timeout: 120_000 }) });
  });
  return urls;
}

test("a slice reads its layers in parts and Export writes the engine's file", async ({ page }) => {
  const urls = await proxy(page);
  await page.addInitScript(() => { Object.defineProperty(window, "showSaveFilePicker", { value: undefined }); });
  await page.goto("/");
  await autoSliceOff(page);
  // A mesh of its own each run: a second UI slice of a mesh the engine already holds is a separate question.
  await page.locator("#file").setInputFiles({ name: "steps.stl", mimeType: "model/stl", buffer: Buffer.from(stepsStl(8 + (Date.now() % 1000) / 1000)) });
  await expect(page.locator("#objectList .obj").first()).toBeVisible({ timeout: 30_000 });
  await page.locator("#slice").click();
  await expect(page.locator("#export")).toHaveAttribute("data-slice", "current", { timeout: 120_000 });
  expect(urls.some((url) => /^\/api\/reply\/[^/]+\/0$/.test(url)), urls.join(" ")).toBe(true);
  expect(Number(await page.locator("#rangeHigh").getAttribute("max"))).toBeGreaterThan(40);

  const [download] = await Promise.all([page.waitForEvent("download"), page.locator("#export").click()]);
  const text = readFileSync(await download.path(), "utf8");
  expect(urls.some((url) => /^\/api\/gcode\/[^/]+\/file$/.test(url)), urls.join(" ")).toBe(true);
  expect(text.startsWith("; generated by Lime Slice")).toBe(true);
  expect(text).toContain("M73 P100 R0\n");
  expect(text.split("\n;LAYER:").length - 1).toBe(Number(await page.locator("#rangeHigh").getAttribute("max")) + 1);
});

test("the engine's filled skeleton is the whole file stamped, byte for byte", async ({ request }) => {
  const body = {
    filename: "dragon.stl",
    dataB64: readFileSync("samples/dragon_2_5.stl").toString("base64"),
    layerHeight: 0.2,
    lineWidth: 0.45,
    baseline: false,
    compare: false,
    includePreview: false,
    includeGcode: false,
  };
  const reply = (await (await request.post(`${api}/api/slice`, { data: body, timeout: 120_000 })).json()) as { gcodeToken: string };
  const path = `${api}/api/gcode/${reply.gcodeToken}`;
  const whole = await (await request.get(path)).text();
  const skeleton = await (await request.get(`${path}/skeleton`)).text();
  expect(skeleton.length * 10).toBeLessThan(whole.length);
  const layers = whole.split("\n;LAYER:").length - 1;
  for (const startOwnsHoming of [false, true]) {
    const meta = {
      now: new Date(2026, 9, 29, 12, 0, 0),
      version: "9.9.9",
      layerSeconds: Array.from({ length: layers }, (_, i) => 1 + (i % 7)),
      layerHeight: 0.2,
      nozzleDiameter: 0.4,
      filamentType: "PLA",
      startGcode: "PRINT_START BED={bed} EXTRUDER={nozzle}\nG92 E0",
      endGcode: "PRINT_END",
      startOwnsHoming,
      heat: { bedC: 60, nozzleC: 210, bedAskC: 70, nozzleAskC: 215 },
      grams: 12.3456,
    };
    const file = await request.post(`${path}/file`, { data: printerGcode({ ...meta, gcode: skeleton }), headers: { "Content-Type": "text/plain" } });
    expect(file.ok()).toBe(true);
    expect(sha(await file.body()), `startOwnsHoming ${startOwnsHoming}`).toBe(sha(printerGcode({ ...meta, gcode: whole })));
  }
  const lost = await request.post(`${path}/file`, { data: skeleton.replace("\u00010\n", ""), headers: { "Content-Type": "text/plain" } });
  expect(lost.status()).toBe(400);
});
