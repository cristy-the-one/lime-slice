import assert from "node:assert/strict";
import { mkdtempSync, readFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fakeEngine } from "./engine.ts";
import { findLust } from "./recipe.ts";
import { bodyHash, parsePlugin, pluginText, readPlugin, writePlugin } from "./plugins.ts";
import { readPluginFile, pluginFileText } from "../src/plugin-file.ts";
import { withPluginData } from "../src/recipe/plugin-data.ts";
import { Session } from "./session.ts";

if (!findLust()) {
  if (process.env.LIME_RECIPE_REQUIRED === "1") throw new Error("lust is required");
  console.log("animation-plugin: skipped (set LIME_LUST)"); process.exit(0);
}
const workspace = mkdtempSync(join(tmpdir(), "lime-animation-share-"));
const sender = mkdtempSync(join(tmpdir(), "lime-animation-sender-"));
const receiver = mkdtempSync(join(tmpdir(), "lime-animation-receiver-"));
process.env.LIME_MCP_WORKSPACE = workspace; process.env.LIME_PLUGINS_DIR = sender;
const code = `use lime_recipe::{anim::*, Session};
fn main() {
  let mut s = Session::start();
  let data = s.data("angles").unwrap();
  let angle = data.get("angle").and_then(|v| v.as_f64()).unwrap();
  let mut a = Animation::new(4);
  a.key(0.0, Pose::rest());
  a.key(1.0, Pose::new().set("Finger", angle));
  s.animate(&a).unwrap();
}
`;
const body = withPluginData(code, { angles: { sha256: "a".repeat(64), bytes: 12, value: { angle: 60 } } });
const header = { plugin: "wave", kind: "animation" as const, title: "Wave", version: 1, description: "Turn a finger.", author: "Test", api: "1.8", "source-sha256": bodyHash(body), created: "2026-11-08", target: "object" as const, params: [] };
const text = pluginText(header, body), parsed = parsePlugin(text);
assert.ok(!("reason" in parsed));
if (!("reason" in parsed)) assert.equal(parsed.header.kind, "animation");
const app = readPluginFile(text);
assert.equal(app?.kind, "animation");
const appText = pluginFileText({ plugin: "wave", kind: "animation", title: "Wave", version: 1, description: "", author: "Test", api: "1.8", sha256: bodyHash(body), created: "2026-11-08", target: "object", params: [] }, body);
assert.equal(readPluginFile(appText)?.kind, "animation");
writePlugin(header, body, sender);
const original = readPlugin("wave", sender);
assert.ok(original && !("reason" in original) && original.header.kind === "animation");
const a = new Session(fakeEngine());
const exported = await a.call("nugget", { action: "export", kind: "plugin", id: "wave" });
assert.equal(exported.ok, true, JSON.stringify(exported));
assert.match(readFileSync(String(exported.path), "utf8"), /\/\/! kind: animation/);
process.env.LIME_PLUGINS_DIR = receiver;
const b = new Session(fakeEngine());
const imported = await b.call("nugget", { action: "save", kind: "plugin", from: String(exported.path) });
assert.equal(imported.ok, true, JSON.stringify(imported));
const saved = readPlugin("wave", receiver);
assert.ok(saved && !("reason" in saved) && saved.header.kind === "animation");
const guide = await b.call("guide", { kind: "animation" });
assert.equal(guide.ok, true); assert.match(String(guide.text), /pose_animate/);
const listed = await b.call("plugin", { action: "list" });
assert.ok(JSON.stringify(listed).includes('"kind":"animation"'));
const wrong = await b.call("recipe_run", { plugin: "wave" });
assert.equal(wrong.ok, false); assert.match(String(wrong.reason), /pose_animate/);
const make = async () => String((await b.call("solid_new", { primitive: "box", dx: 2, dy: 2, dz: 2 })).object);
const root = await make(), finger = await make(); b.find(finger)!.name = "Finger";
assert.equal((await b.call("model_place", { object: finger, to: root, x: 4 })).ok, true);
assert.equal((await b.call("model_place", { object: finger, joint: { kind: "hinge", pivot: [0, 0, 0], axis: [0, 0, 1] } })).ok, true);
const run = await b.call("pose_animate", { object: finger, plugin: "wave" });
assert.equal(run.ok, true, JSON.stringify(run)); assert.equal(run.frames, 4);
const rendered = await b.call("pose_animate", { object: finger, plugin: "wave", longEdge: 32, out: { gif: "wave.gif" } });
assert.equal(rendered.ok, true, JSON.stringify(rendered));
const direct = await b.call("pose_animate", { object: finger, source: `\n${body}`, name: "direct-wave", longEdge: 32, out: { gif: "direct.gif" } });
assert.equal(direct.ok, true, JSON.stringify(direct));
const project = await b.call("project_save", { name: "with-animation.lime" });
assert.equal(project.ok, true, JSON.stringify(project));
process.env.LIME_PLUGINS_DIR = mkdtempSync(join(tmpdir(), "lime-animation-empty-"));
const reopened = new Session(fakeEngine());
const opened = await reopened.call("project_open", { path: String(project.path) });
assert.equal(opened.ok, true, JSON.stringify(opened));
assert.equal(reopened.animations.get("wave")?.assembly, b.assemblies[0]!.id);
const held = reopened.animations.get("wave")!;
reopened.animations.set("wave", { ...held, api: "9.0" });
const future = await reopened.call("pose_animate", { object: finger, plugin: "wave" });
assert.equal(future.ok, false); assert.equal(future.code, "plugin-unsupported");
reopened.animations.set("wave", held);
const restored = await reopened.call("pose_animate", { object: finger, plugin: "wave" });
assert.equal(restored.ok, true, JSON.stringify(restored));
assert.equal(restored.frames, 4);
const projectList = await reopened.call("plugin", { action: "list" });
assert.ok(JSON.stringify(projectList).includes('"kind":"animation"'), JSON.stringify(projectList));
const reexported = await reopened.call("nugget", { action: "export", kind: "plugin", id: "wave" });
assert.equal(reexported.ok, true, JSON.stringify(reexported));
assert.match(readFileSync(String(reexported.path), "utf8"), /\/\/! kind: animation/);
const directExport = await reopened.call("nugget", { action: "export", kind: "plugin", id: "direct-wave" });
assert.equal(directExport.ok, true, JSON.stringify(directExport));
const directText = readFileSync(String(directExport.path), "utf8");
const directParsed = parsePlugin(directText);
assert.ok(!("reason" in directParsed) && directParsed.matches && directParsed.header.kind === "animation");
const directImport = await reopened.call("nugget", { action: "save", kind: "plugin", from: String(directExport.path) });
assert.equal(directImport.ok, true, JSON.stringify(directImport));
console.log("animation-plugin: kind, export, import, dispatch and playback passed");
