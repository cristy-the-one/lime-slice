/** A stopped multi-part recipe keeps its checkpoint and resumes without duplicating parts. */
import { mkdtempSync, renameSync, unlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { fakeEngine, loadEngineWorker } from "./engine.ts";
import { findLust } from "./recipe.ts";
import { Session } from "./session.ts";
import { autosavePath } from "./autosave.ts";
import { checkpointSignature } from "./recipe-checkpoint.ts";

if (!findLust()) {
  if (process.env.LIME_RECIPE_REQUIRED === "1") throw new Error("recipe checkpoint test needs lust");
  console.log("recipe checkpoint: skipped (needs lust)");
  process.exit(0);
}
process.env.LIME_MCP_WORKSPACE = mkdtempSync(join(tmpdir(), "lime-recipe-checkpoint-"));
writeFileSync(join(process.env.LIME_MCP_WORKSPACE, "values.json"), "[1,2,3]");
process.env.LIME_MCP_REPLY_S = "0.05";
process.env.LIME_MCP_FAKE_MODEL_MS = "300";
const makeEngine = () => {
  if (process.env.LIME_CHECKPOINT_REAL !== "1") return fakeEngine();
  const engine = loadEngineWorker(fileURLToPath(new URL("..", import.meta.url)));
  const modelTree = engine.modelTree.bind(engine);
  engine.modelTree = async (body) => {
    if (/"call":"(apply|probe)"/.test(body)) await new Promise((resolve) => setTimeout(resolve, 300));
    return modelTree(body);
  };
  return engine;
};
const session = new Session(makeEngine());
const source = `use lime_recipe::{ops, Session};
fn main() {
    let mut s = Session::start();
    let _first = s.data("values").unwrap();
    let a = s.solid_new(ops::cuboid(10.0, 10.0, 2.0)).unwrap();
    s.checkpoint().unwrap();
    let _again = s.data("values").unwrap();
    s.apply(&a, ops::boolean("fuse", ops::cuboid(1.0, 1.0, 1.0), [0.0, 0.0, 2.0])).unwrap();
    let b = s.solid_new(ops::cuboid(11.0, 10.0, 2.0)).unwrap();
    s.checkpoint().unwrap();
    s.apply(&b, ops::boolean("fuse", ops::cuboid(1.0, 1.0, 1.0), [0.0, 0.0, 2.0])).unwrap();
    let _c = s.solid_new(ops::cuboid(12.0, 10.0, 2.0)).unwrap();
    s.done(&a);
}
`;
const first = await session.call("recipe_run", { name: "checkpoint-test", source, timeoutS: 30 });
if (first.status !== "running" || typeof first.job !== "string") throw new Error(`recipe did not detach: ${JSON.stringify(first)}`);
for (let i = 0; i < 500 && !session.recipeCheckpoints.has("checkpoint-test"); i += 1) await new Promise((resolve) => setTimeout(resolve, 20));
if (!session.recipeCheckpoints.has("checkpoint-test")) throw new Error("recipe never saved its checkpoint");
let stopped = await session.call("slice_cancel", { job: first.job });
while (stopped.status === "cancelling") stopped = await session.call("slice_wait", { job: first.job, timeoutS: 1 });
if (stopped.ok !== false || session.objects.length !== 1) throw new Error(`checkpoint did not survive cancellation: ${JSON.stringify(stopped)}`);
const saved = session.objects[0]!.id;
if (checkpointSignature(session.objects[0]!) !== session.recipeCheckpoints.get("checkpoint-test")!.objects[0]!.signature) throw new Error("cancel did not restore the checkpointed part");
let changedSource = await session.call("recipe_run", { name: "checkpoint-test", source: source.replace("12.0, 10.0", "13.0, 10.0") });
while (changedSource.status === "running") changedSource = await session.call("slice_wait", { job: changedSource.job, timeoutS: 1 });
if (changedSource.ok !== false || !String(changedSource.reason).includes("different source")) throw new Error(`changed source resumed: ${JSON.stringify(changedSource)}`);
const supports = session.settings.supports;
await session.call("settings_set", { values: { supports: !supports } });
let changedSettings = await session.call("recipe_run", { name: "checkpoint-test", source });
while (changedSettings.status === "running") changedSettings = await session.call("slice_wait", { job: changedSettings.job, timeoutS: 1 });
if (changedSettings.ok !== false || !String(changedSettings.reason).includes("settings")) throw new Error(`changed settings resumed: ${JSON.stringify(changedSettings)}`);
await session.call("settings_set", { values: { supports } });
await session.call("model_place", { object: saved, x: 2, frame: "model" });
let changedPart = await session.call("recipe_run", { name: "checkpoint-test", source });
while (changedPart.status === "running") changedPart = await session.call("slice_wait", { job: changedPart.job, timeoutS: 1 });
if (changedPart.ok !== false || !String(changedPart.reason).includes("changed after it was saved")) throw new Error(`changed part resumed: ${JSON.stringify(changedPart)}`);
await session.call("model_place", { object: saved, x: 0, frame: "model" });
unlinkSync(join(process.env.LIME_MCP_WORKSPACE, "values.json"));
const firstEventCount = session.recipeCheckpoints.get("checkpoint-test")!.events.length;
const secondRun = await session.call("recipe_run", { name: "checkpoint-test", source, timeoutS: 30 });
if (secondRun.status !== "running" || typeof secondRun.job !== "string") throw new Error(`second run did not detach: ${JSON.stringify(secondRun)}`);
for (let i = 0; i < 500 && (session.recipeCheckpoints.get("checkpoint-test")?.events.length ?? 0) <= firstEventCount; i += 1) await new Promise((resolve) => setTimeout(resolve, 20));
if ((session.recipeCheckpoints.get("checkpoint-test")?.objects.length ?? 0) !== 2) throw new Error("second checkpoint was not saved");
let stoppedAgain = await session.call("slice_cancel", { job: secondRun.job });
while (stoppedAgain.status === "cancelling") stoppedAgain = await session.call("slice_wait", { job: secondRun.job, timeoutS: 1 });
if (stoppedAgain.ok !== false || Number(session.objects.length) !== 2) throw new Error(`second checkpoint did not survive: ${JSON.stringify(stoppedAgain)}`);
let resumed = await session.call("recipe_run", { name: "checkpoint-test", source, timeoutS: 30 });
while (resumed.status === "running") resumed = await session.call("slice_wait", { job: resumed.job, timeoutS: 1 });
if (resumed.ok !== true || Number(session.objects.length) !== 3 || session.objects[0]!.id !== saved || session.recipeCheckpoints.has("checkpoint-test")) throw new Error(`resume duplicated or lost parts: ${JSON.stringify(resumed)}`);
// A restarted server adopts its own last autosave before resuming by name.
process.env.LIME_MCP_WORKSPACE = mkdtempSync(join(tmpdir(), "lime-checkpoint-restart-"));
writeFileSync(join(process.env.LIME_MCP_WORKSPACE, "values.json"), "[1,2,3]");
const beforeRestart = new Session(makeEngine());
const running = await beforeRestart.call("recipe_run", { name: "restart-test", source, timeoutS: 30 });
if (running.status !== "running" || typeof running.job !== "string") throw new Error(`restart recipe did not detach: ${JSON.stringify(running)}`);
for (let i = 0; i < 500 && !beforeRestart.recipeCheckpoints.has("restart-test"); i += 1) await new Promise((resolve) => setTimeout(resolve, 20));
if (!beforeRestart.recipeCheckpoints.has("restart-test")) throw new Error(`restart recipe never saved its checkpoint: ${JSON.stringify(beforeRestart.workJobs.map((row) => ({ result: row.result, error: row.error, stage: row.ctx.stage })))}`);
let interrupted = await beforeRestart.call("slice_cancel", { job: running.job });
while (interrupted.status === "cancelling") interrupted = await beforeRestart.call("slice_wait", { job: running.job, timeoutS: 1 });
await beforeRestart.autosaveSettled();
unlinkSync(join(process.env.LIME_MCP_WORKSPACE, "values.json"));
renameSync(autosavePath()!, join(process.env.LIME_MCP_WORKSPACE, "autosave-2147483646.lime"));
const restarted = new Session(makeEngine());
const info = await restarted.call("session_info", {});
if (!Array.isArray(info.recipeCheckpoints) || !info.recipeCheckpoints.includes("restart-test") || JSON.stringify(info.autosave).includes("checkpoints")) throw new Error(`checkpoint discovery exposed its journal: ${JSON.stringify(info)}`);
let after = await restarted.call("recipe_run", { name: "restart-test", timeoutS: 30 });
while (after.status === "running") after = await restarted.call("slice_wait", { job: after.job, timeoutS: 1 });
if (after.ok !== true || restarted.objects.length !== 3 || restarted.objects[0]!.id !== "obj_1") throw new Error(`restart did not resume: ${JSON.stringify(after)}`);
process.env.LIME_MCP_WORKSPACE = mkdtempSync(join(tmpdir(), "lime-checkpoint-timeout-"));
writeFileSync(join(process.env.LIME_MCP_WORKSPACE, "values.json"), "[1,2,3]");
process.env.LIME_MCP_FAKE_MODEL_MS = "900";
const timed = new Session(fakeEngine());
let timedOut = await timed.call("recipe_run", { name: "timeout-test", source, timeoutS: 1 });
while (timedOut.status === "running") timedOut = await timed.call("slice_wait", { job: timedOut.job, timeoutS: 1 });
if (timedOut.ok !== false || !String(timedOut.reason).includes("limit") || timed.objects.length !== 1 || !timed.recipeCheckpoints.has("timeout-test")) throw new Error(`timeout lost checkpoint: ${JSON.stringify(timedOut)}`);
process.env.LIME_MCP_FAKE_MODEL_MS = "0";
let afterTimeout = await timed.call("recipe_run", { name: "timeout-test", timeoutS: 30 });
while (afterTimeout.status === "running") afterTimeout = await timed.call("slice_wait", { job: afterTimeout.job, timeoutS: 1 });
if (afterTimeout.ok !== true || Number(timed.objects.length) !== 3) throw new Error(`timeout resume failed: ${JSON.stringify(afterTimeout)}`);
console.log("recipe checkpoint: ok");
process.exit(0);
