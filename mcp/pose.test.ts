import assert from "node:assert/strict";
import { mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fakeEngine } from "./engine.ts";
import { Session } from "./session.ts";
import { validateTool } from "./schema.ts";

process.env.LIME_MCP_WORKSPACE = mkdtempSync(join(tmpdir(), "lime-pose-"));
const s = new Session(fakeEngine());
const call = (name: string, input: Record<string, unknown> = {}) => s.call(name, input);
const make = async () => String((await call("solid_new", { primitive: "box", dx: 2, dy: 2, dz: 2 })).object);
const root = await make(), leg = await make(), claw = await make();
assert.equal((await call("model_place", { object: leg, to: root, x: 10 })).ok, true);
assert.equal((await call("model_place", { object: claw, to: leg, x: 10 })).ok, true);
const hinge = { kind: "hinge", pivot: [0, 0, 0], axis: [0, 0, 2], min: -90, max: 90 };
assert.equal(validateTool("model_place", { object: leg, joint: hinge }), null);
assert.equal(validateTool("model_place", { object: leg, joint: null }), null);
assert.equal(validateTool("model_place", { object: leg, reach: { at: [1, 0, 0], to: [10, 10, 0] } }), null);
assert.equal((await call("model_place", { object: leg, joint: hinge })).ok, true);
assert.equal((await call("model_place", { object: claw, joint: hinge })).ok, true);
const at = (id: string) => s.find(id)!.modelPose.t;
const before = structuredClone(s.assemblies);
const rootBefore = [...at(root)], layout = s.objects.map((o) => structuredClone(o.offset));
const bad = await call("model_place", { object: leg, joint: { ...hinge, axis: [0, 0, 0] }, angle: 20 });
assert.equal(bad.ok, false); assert.deepEqual(s.assemblies, before);
assert.equal((await call("model_place", { object: root, joint: { kind: "ball", pivot: [0, 0, 0] } })).ok, false);
// A root may take a hinge: it turns on the plate (docs/plan-gear-kinds.md). Undo puts the fixed root back.
assert.equal((await call("model_place", { object: root, joint: hinge })).ok, true);
assert.equal((await call("plate_undo")).ok, true);
assert.deepEqual(s.assemblies, before);
assert.equal((await call("model_place", { object: leg, angle: 5, reach: { at: [0, 0, 0], to: [0, 1, 0] } })).ok, false);
const turned = await call("model_place", { object: leg, angle: 120 });
assert.equal(turned.ok, true);
assert.equal(s.assemblies[0]!.members.find((m) => m.object === leg)!.joint!.kind, "hinge");
assert.ok(Math.abs(at(claw)[0] - 10) < 1e-6 && Math.abs(at(claw)[1] - 10) < 1e-6);
assert.equal((await call("plate_undo")).ok, true);
assert.deepEqual(s.assemblies, before);
assert.ok(Math.abs(at(claw)[0] - 20) < 1e-6 && Math.abs(at(claw)[1]) < 1e-6);
assert.equal((await call("plate_redo")).ok, true);
assert.ok(Math.abs(at(claw)[1] - 10) < 1e-6);
assert.equal((await call("plate_undo")).ok, true);
assert.equal((await call("model_place", { object: claw, reach: { at: { anchor: "bad" }, to: [1, 2, 3] } })).ok, false);
const unreachable = await call("model_place", { object: claw, reach: { at: [0, 0, 0], to: [100, 100, 0] } });
assert.equal(unreachable.ok, true); assert.equal(unreachable.reached, false); assert.ok(Number(unreachable.distanceMm) > 0.05);
assert.equal((await call("plate_undo")).ok, true);
const reached = await call("model_place", { object: claw, reach: { at: [0, 0, 0], to: [10, 10, 0] } });
assert.equal(reached.ok, true); assert.equal(reached.reached, true);
assert.ok(Number(reached.distanceMm) <= 0.05); assert.ok(Array.isArray(reached.angles));
assert.deepEqual(at(root), rootBefore); assert.deepEqual(s.objects.map((o) => o.offset), layout);
const list = await call("plate_list");
assert.ok((list.objects as { object: string; joint?: unknown }[]).find((row) => row.object === claw)?.joint);
const info = await call("session_info");
assert.ok(JSON.stringify(info.assemblies).includes('"joint"'));
assert.ok(String((await call("guide", { kind: "pose" })).text).includes("reach"));
assert.equal((await call("model_place", { object: claw, joint: null })).ok, true);
assert.equal((await call("model_place", { object: claw, angle: 10 })).ok, false);
assert.equal((await call("plate_undo")).ok, true);
assert.ok(s.assemblies[0]!.members.find((m) => m.object === claw)?.joint);
assert.equal((await call("model_place", { object: claw, joint: { kind: "ball", pivot: [0, 0, 0], cone: 40 } })).ok, true);
assert.equal((await call("model_place", { object: claw, angle: 3 })).ok, false);
const combined = await call("model_place", { object: claw, joint: hinge, angle: 20 });
assert.equal(combined.ok, true);
assert.equal((combined.joint as { angle: number }).angle, 20);
const saved = await call("project_save", { name: "posed.lime" });
assert.equal(saved.ok, true);
const reopened = new Session(fakeEngine());
assert.equal((await reopened.call("project_open", { path: String(saved.path) })).ok, true);
assert.ok(reopened.assemblies.some((assembly) => assembly.members.some((member) => member.joint?.kind === "hinge")));
// A joint's alignment removes its rest twist, even after it has turned.
const rig = new Session(fakeEngine());
const makeRig = async () => String((await rig.call("solid_new", { primitive: "box", dx: 2, dy: 2, dz: 2 })).object);
const base = await makeRig(), finger = await makeRig();
await rig.call("model_place", { object: finger, to: base, turnZ: 15 });
await rig.call("model_place", { object: finger, joint: hinge });
const rowOf = async () => ((await rig.call("plate_list", {})).objects as { object: string; aligned?: number }[]).find((row) => row.object === finger)!;
assert.ok(Math.abs((await rowOf()).aligned! + 15) < 1e-7);
const short = await rig.call("model_place", { object: finger, angle: 20, reply: "angles" });
assert.equal(short.ok, true);
assert.deepEqual(Object.keys(short).sort(), ["angles", "ok"]);
assert.ok(JSON.stringify(short).length < 5000);
assert.ok(Math.abs((await rowOf()).aligned! + 15) < 1e-7);
const shortReach = await rig.call("model_place", { object: finger, reach: { at: [1, 0, 0], to: [0, 1, 0] }, reply: "angles" });
assert.equal(shortReach.ok, true);
assert.ok("distanceMm" in shortReach && !Object.hasOwn(shortReach, "moved"));
assert.equal((await rig.call("model_place", { object: finger, x: 10, reply: "angles" })).ok, false);
assert.equal((await rig.call("model_place", { objects: [finger], to: base, reply: "angles" })).ok, false);
console.log("MCP pose: joint, turn, reach, readback, refusals and undo ok");
