let failed = 0;
function check(name: string, ok: boolean, detail = "") {
  if (ok) {
    console.log(name);
    return;
  }
  failed += 1;
  console.error(`FAIL ${name}${detail ? `: ${detail}` : ""}`);
}

const gcode = [
  "; generated by Lime Slice — FDM strategy blender",
  "G28",
  "G1 X0 Y0 E1",
  ";LAYER:0",
  "G1 X1",
  "M106 S0",
  "M104 S0",
  "M140 S0",
  "; TIME:12.0s FILAMENT_MM:100.00 FILAMENT_G:0.300",
  "",
].join("\n");

const library = builtinLibrary();
const lime = library.printers.find((row) => row.id === "lime-220")!;
const pla = library.filaments.find((row) => row.id === "lime-pla")!;
const petg = library.filaments.find((row) => row.id === "lime-petg")!;
const ir3 = library.printers.find((row) => row.id === "ideaformer-ir3-v2")!;
const now = new Date(2020, 0, 2, 3, 4, 5);
const plaGrams = filamentGrams(100, { filamentDiameter: pla.diameterMm, filamentDensityGCm3: pla.densityGCm3, filamentCostPerKg: pla.costPerKg });
const petgGrams = filamentGrams(100, { filamentDiameter: petg.diameterMm, filamentDensityGCm3: petg.densityGCm3, filamentCostPerKg: petg.costPerKg });

function appFile(grams: number, printer: typeof lime, filament: typeof pla): string {
  return printerGcode({
    gcode,
    grams,
    now,
    version: appVersion(),
    layerSeconds: [1],
    layerHeight: 0.2,
    nozzleDiameter: 0.4,
    filamentType: filament.material,
    startGcode: spliceText(printer.startGcode, legacyStockStart(printer.name)),
    endGcode: spliceText(printer.endGcode, legacyStockEnd(printer.name)),
    startOwnsHoming: printer.startOwnsHoming,
    heat: heatFor(printer, filament.nozzleTemp, filament.bedTemp),
  });
}

const plaFile = exportGcode({
  gcode,
  grams: plaGrams,
  now,
  layerSeconds: [1],
  layerHeight: 0.2,
  nozzleDiameter: 0.4,
  filamentType: pla.material,
  printerName: lime.name,
  startGcode: lime.startGcode,
  endGcode: lime.endGcode,
  startOwnsHoming: lime.startOwnsHoming,
  heat: heatFor(lime, pla.nozzleTemp, pla.bedTemp),
});
check("lime 220 PLA matches the app's export function", plaFile === appFile(plaGrams, lime, pla));
check("the footer grams are the filament's, not 1.24 from a different density", plaFile.includes(`FILAMENT_G:${plaGrams.toFixed(3)}`) && pla.densityGCm3 === 1.24);

const petgFile = exportGcode({
  gcode,
  grams: petgGrams,
  now,
  layerSeconds: [1],
  layerHeight: 0.2,
  nozzleDiameter: 0.4,
  filamentType: petg.material,
  printerName: lime.name,
  startGcode: lime.startGcode,
  endGcode: lime.endGcode,
  startOwnsHoming: lime.startOwnsHoming,
  heat: heatFor(lime, petg.nozzleTemp, petg.bedTemp),
});
check("PETG uses 1.27 and matches the app function", petg.densityGCm3 === 1.27 && petgFile === appFile(petgGrams, lime, petg) && petgFile.includes(`FILAMENT_G:${petgGrams.toFixed(3)}`) && !petgFile.includes("FILAMENT_G:0.300"));

const ir3File = exportGcode({
  gcode,
  grams: plaGrams,
  now,
  layerSeconds: [1],
  layerHeight: 0.2,
  nozzleDiameter: 0.4,
  filamentType: pla.material,
  printerName: ir3.name,
  startGcode: ir3.startGcode,
  endGcode: ir3.endGcode,
  startOwnsHoming: ir3.startOwnsHoming,
  heat: heatFor(ir3, pla.nozzleTemp, pla.bedTemp),
});
check("the IR3 V2 start G-code is in the export", ir3.startOwnsHoming && ir3File.includes("PRINT_START") && ir3File === appFile(plaGrams, ir3, pla));

// A belt body: supports touch the belt at 0.283, the part's wall at 1.414. The IR3 V2's belt is zeroed
// on the line whose far edge reaches the middle of that wall: 1.414 less half of a 1.2026 mm line.
const beltGcode = [
  "; generated by Lime Slice — FDM strategy blender",
  "G28",
  "; belt: angle 45 axis Z dir +1",
  ";LAYER:0 Z:0.283 H:0.200 ",
  ";TYPE:SUPPORT",
  "G1 X1 Y0.199 E1 F1800",
  ";LAYER:5 Z:1.414 H:0.200 ",
  ";TYPE:OUTER",
  "G1 X2 Y0.200 E2 F1800",
  "M106 S0",
  "M104 S0",
  "M140 S0",
  "; TIME:12.0s FILAMENT_MM:100.00 FILAMENT_G:0.300",
  "",
].join("\n");
const beltFile = exportGcode({
  gcode: beltGcode,
  grams: plaGrams,
  now,
  layerSeconds: [1],
  layerHeight: 0.2,
  nozzleDiameter: 0.4,
  filamentType: pla.material,
  printerName: ir3.name,
  startGcode: ir3.startGcode,
  endGcode: ir3.endGcode,
  startOwnsHoming: ir3.startOwnsHoming,
  heat: heatFor(ir3, pla.nozzleTemp, pla.bedTemp),
  filamentDiameter: pla.diameterMm,
});
check("the IR3 V2 export zeroes the belt on the line against the part", beltFile.split("\n").includes("G92 E0 Z0.813") && !beltFile.includes("{purge_line_z}"));
check("M73 lines come from the shared printer file", plaFile.includes("M73 ") && appFile(plaGrams, lime, pla).split("\n").filter((line) => line.startsWith("M73 ")).join("\n") === plaFile.split("\n").filter((line) => line.startsWith("M73 ")).join("\n"));
check("the pinned clock is in the generated-by line", plaFile.includes("2020-01-02") && plaFile.includes(appVersion()));

// export_3mf {object}: only that object, as posed on the plate, and the reply says which objects are in the file.
{
  const workspace = mkdtempSync(join(tmpdir(), "lime-export-"));
  process.env.LIME_MCP_WORKSPACE = workspace;
  const cube = fileURLToPath(new URL("../samples/calibration_cube_20mm.stl", import.meta.url));
  const session = new Session(fakeEngine());
  const first = await session.call("mesh_import", { path: cube });
  await session.call("object_place", { object: first.object, centreX: 40, centreY: 40 });
  const second = await session.call("mesh_import", { path: cube });
  await session.call("object_place", { object: second.object, centreX: 150, centreY: 150 });
  const read = (path: string) => {
    const text = readFileSync(path).toString("latin1");
    const xs = [...text.matchAll(/<vertex x="([-0-9.e]+)"/g)].map((row) => Number(row[1]));
    return { objects: (text.match(/<object /g) ?? []).length, xs };
  };
  const whole = await session.call("export_3mf", { name: "both.3mf" });
  const both = read(String(whole.path));
  check("export_3mf without object writes every object and names them", whole.ok === true && both.objects === 2 && (whole.written as unknown[]).length === 2 && /^Wrote 2 objects: /.test(String(whole.note)), JSON.stringify(whole));
  const one = await session.call("export_3mf", { name: "one.3mf", object: second.object });
  const single = read(String(one.path));
  check("export_3mf {object} writes one object", one.ok === true && single.objects === 1, JSON.stringify(one) + JSON.stringify(single.objects));
  check("that object is posed where it stands on the plate", single.xs.length > 0 && single.xs.every((x) => x > 139 && x < 161), JSON.stringify(single.xs.slice(0, 4)));
  check("the reply names the object written and the one left out", JSON.stringify((one.written as { object: string }[]).map((row) => row.object)) === JSON.stringify([second.object]) && String(one.note).includes(String(second.object)) && String(one.note).includes("1 other object is not in the file"), String(one.note));
  const refused = await session.call("export_3mf", { name: "none.3mf", object: "obj_99" });
  check("an object that is not on the plate is refused, and nothing is written", refused.ok === false && refused.code === "no-object" && !existsSync(join(workspace, "none.3mf")), JSON.stringify(refused));
}

// export {scope, format, name}: every scope and format writes a file, and the three old tools
// write the same bytes as export for the same request.
{
  const workspace = mkdtempSync(join(tmpdir(), "lime-one-export-"));
  process.env.LIME_MCP_WORKSPACE = workspace;
  const cube = fileURLToPath(new URL("../samples/calibration_cube_20mm.stl", import.meta.url));
  const session = new Session(fakeEngine());
  const first = await session.call("mesh_import", { path: cube });
  const second = await session.call("mesh_import", { path: cube });
  check("two meshes are on the plate", first.ok === true && second.ok === true, JSON.stringify(first));
  const meshFormats = ["stl", "3mf", "obj", "glb"] as const;
  for (const format of meshFormats) {
    const wrote = await session.call("export", { scope: "part", format, object: String(first.object), name: `part-${format}` });
    check(`part ${format} writes a file`, wrote.ok === true && existsSync(String(wrote.path)) && readFileSync(String(wrote.path)).byteLength > 0, JSON.stringify(wrote));
  }
  const linked = await session.call("model_place", { object: second.object, to: first.object });
  check("the two meshes become an assembly", linked.ok === true, JSON.stringify(linked));
  for (const format of [...meshFormats, "pose"] as const) {
    const wrote = await session.call("export", { scope: "assembly", format, assembly: String(first.object), name: `asm-${format}` });
    check(`assembly ${format} writes a file`, wrote.ok === true && existsSync(String(wrote.path)), JSON.stringify(wrote));
    const plate = await session.call("export", { scope: "plate-assembled", format, name: `plate-${format}` });
    check(`plate-assembled ${format} writes a file`, plate.ok === true && existsSync(String(plate.path)), JSON.stringify(plate));
  }
  for (const format of ["3mf", "stl"] as const) {
    const wrote = await session.call("export", { scope: "plate-print", format, name: `bed-${format}`, ...(format === "stl" ? { stl: "each" } : {}) });
    check(`plate-print ${format} writes a file`, wrote.ok === true && existsSync(String(wrote.path)) && readFileSync(String(wrote.path)).byteLength > 0, JSON.stringify(wrote));
  }
  const old3mf = await session.call("export_3mf", { name: "old-plate.3mf" });
  const new3mf = await session.call("export", { scope: "plate-print", format: "3mf", name: "new-plate.3mf" });
  check("export_3mf and export plate-print 3mf write the same bytes", old3mf.ok === true && new3mf.ok === true && readFileSync(String(old3mf.path)).equals(readFileSync(String(new3mf.path))), JSON.stringify({ old3mf, new3mf }));
  const oldPose = await session.call("pose_export", { assembly: String(first.object), format: "stl", path: "old-pose.stl" });
  const newPose = await session.call("export", { scope: "assembly", format: "stl", assembly: String(first.object), name: "new-pose.stl" });
  check("pose_export and export assembly stl write the same bytes", oldPose.ok === true && newPose.ok === true && readFileSync(String(oldPose.path)).equals(readFileSync(String(newPose.path))), JSON.stringify({ oldPose, newPose }));

  const solids = new Session(fakeEngine());
  const box = await solids.call("solid_new", { primitive: "box", dx: 10, dy: 10, dz: 10, name: "body" });
  const lid = await solids.call("solid_new", { primitive: "box", dx: 8, dy: 8, dz: 4, name: "lid" });
  check("two solids are on the plate", box.ok === true && lid.ok === true, JSON.stringify(box));
  await solids.call("model_place", { object: lid.object, to: box.object });
  const oldStep = await solids.call("model_export_step", { object: box.object, name: "old-body.step" });
  const newStep = await solids.call("export", { scope: "part", format: "step", object: String(box.object), name: "new-body.step" });
  check("model_export_step and export part step write the same bytes", oldStep.ok === true && newStep.ok === true && readFileSync(String(oldStep.path)).equals(readFileSync(String(newStep.path))), JSON.stringify({ oldStep, newStep }));
  const oldAsm = await solids.call("pose_export", { assembly: String(box.object), format: "step", path: "old-asm.step" });
  const newAsm = await solids.call("export", { scope: "assembly", format: "step", assembly: String(box.object), name: "new-asm.step" });
  check("pose_export and export assembly step write the same bytes", oldAsm.ok === true && newAsm.ok === true && readFileSync(String(oldAsm.path)).equals(readFileSync(String(newAsm.path))), JSON.stringify({ oldAsm, newAsm }));
  const plateStep = await solids.call("export", { scope: "plate-assembled", format: "step", name: "plate.step" });
  check("plate-assembled step writes a file", plateStep.ok === true && existsSync(String(plateStep.path)) && readFileSync(String(plateStep.path)).byteLength > 0, JSON.stringify(plateStep));
}

if (failed) {
  console.error(`${failed} failed`);
  process.exit(1);
}
console.log("export: ok");
