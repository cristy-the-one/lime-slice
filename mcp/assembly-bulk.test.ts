import { mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fakeEngine } from "./engine.ts";
import { Session } from "./session.ts";

process.env.LIME_MCP_WORKSPACE = mkdtempSync(join(tmpdir(), "lime-assembly-bulk-"));
const s = new Session(fakeEngine());
const make = async () => String((await s.call("solid_new", { primitive: "box", dx: 2, dy: 2, dz: 2 })).object);
const root = await make();
const a = await make();
const b = await make();
await s.call("model_place", { object: a, x: 10, z: 5 });
await s.call("model_place", { object: b, x: -7, z: 9 });
const before = [a, b].map((id) => [...s.find(id)!.modelPose.t]);
const invalid = await s.call("model_place", { objects: [a, "missing"], to: root });
if (invalid.ok !== false || s.assemblies.length !== 0) throw new Error(`bulk failure was not atomic: ${JSON.stringify(invalid)}`);
const joined = await s.call("model_place", { objects: [a, b], to: root, compact: true });
if (joined.ok !== true || JSON.stringify([a, b].map((id) => s.find(id)!.modelPose.t)) !== JSON.stringify(before)) throw new Error(`bulk join moved parts: ${JSON.stringify(joined)}`);
await s.call("model_place", { object: root, x: 4 });
const positions = [a, b].map((id) => s.find(id)!.modelPose.t);
if (positions[0]![0] !== 14 || positions[1]![0] !== -3) throw new Error(`joined parts did not follow the root: ${JSON.stringify(positions)}`);
const c = await make();
const d = await make();
await s.call("model_place", { object: c, x: 30 });
await s.call("model_place", { object: d, x: 35 });
const second = await s.call("model_place", { objects: [d], to: c, assembly: "second" });
const merged = await s.call("assembly_merge", { from: second.assembly, into: joined.assembly });
if (merged.ok !== true || Number(s.assemblies.length) !== 1 || s.find(c)!.modelPose.t[0] !== 30 || s.find(d)!.modelPose.t[0] !== 35) throw new Error(`merge changed a pose: ${JSON.stringify(merged)}`);
await s.call("model_place", { object: root, x: 5 });
if (s.find(c)!.modelPose.t[0] !== 31 || s.find(d)!.modelPose.t[0] !== 36) throw new Error("merged assembly did not follow its destination root");
const same = await s.call("assembly_merge", { from: joined.assembly, into: joined.assembly });
if (same.ok !== false || Number(s.assemblies.length) !== 1) throw new Error("merging an assembly with itself should be refused");
// Existing placement operations must not erase joint data loaded from a project.
const jointMember = s.assemblies[0]!.members.find((row) => row.object === a)!;
jointMember.joint = { kind: "hinge", pivot: [0, 0, 0], axis: [0, 0, 1], min: -30, max: 60, angle: 10 };
const movedJoint = await s.call("model_place", { object: a, x: 11 });
if (movedJoint.ok !== true || s.assemblies[0]!.members.find((row) => row.object === a)?.joint?.kind !== "hinge") throw new Error("single placement erased the joint");
const relinkedJoint = await s.call("model_place", { objects: [a], to: b });
if (relinkedJoint.ok !== true || s.assemblies[0]!.members.find((row) => row.object === a)?.joint?.kind !== "hinge") throw new Error("bulk placement erased the joint");
console.log("bulk assembly placement: ok");
