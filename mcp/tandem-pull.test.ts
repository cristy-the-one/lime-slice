import { strict as assert } from "node:assert";
import { createServer } from "node:http";
import { mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { fakeEngine } from "./engine.ts";
import { Session } from "./session.ts";
import { mirror } from "./bridge-client.ts";

process.env.LIME_MCP_WORKSPACE = mkdtempSync(join(tmpdir(), "lime-tandem-pull-"));
const session = new Session(fakeEngine());
const path = fileURLToPath(new URL("../samples/calibration_cube_20mm.stl", import.meta.url));
const created = await session.call("mesh_import", { path });
const obj = session.find(String(created.object));
assert.ok(obj);
const base = { name: obj.name, scalePercent: obj.scale * 100, centered: obj.centered, offset: { ...obj.offset }, orient: [...obj.orient], meshHash: session.meshHashOf(obj.bytes) };
const changed = { object: obj.id, name: obj.name, scalePercent: base.scalePercent, centered: base.centered, offset: { ...base.offset, x: base.offset.x + 12 }, orient: base.orient, meshChanged: false, base };
const context: Record<string, unknown> = { mirrorSession: session.bridgeSession, mirrorSeq: session.bridgePlateSeq, gesture: false, editing: false, humanChangesTruncated: false, humanChanges: [changed] };
const server = createServer((request, response) => {
  response.setHeader("x-lime-bridge-features", "open tandem-context");
  response.setHeader("x-lime-bridge-instance", "test-window");
  if (request.method === "GET") response.end(JSON.stringify(context));
  else { request.resume(); response.writeHead(204).end(); }
});
await new Promise<void>((resolve) => server.listen(0, "127.0.0.1", resolve));
const address = server.address();
if (!address || typeof address === "string") throw new Error("Expected TCP listener");
process.env.LIME_MCP_BRIDGE = `http://127.0.0.1:${address.port}/`;
process.env.LIME_MCP_BRIDGE_TOKEN = "test-token";
const pulled = await session.call("tandem_pull", {});
assert.equal(pulled.ok, true);
assert.deepEqual(pulled.changed, [obj.id]);
assert.equal(obj.offset.x, changed.offset.x);
context.mirrorSeq = session.bridgePlateSeq;
assert.equal((await session.call("tandem_pull", {})).ok, false, "stale baseline is refused");
assert.equal((await session.call("plate_undo", {})).ok, true);
context.mirrorSeq = session.bridgePlateSeq;
assert.equal(obj.offset.x, base.offset.x, "pull is undoable");
context.gesture = true;
assert.equal((await session.call("tandem_pull", {})).ok, false, "active gestures are refused");
context.gesture = false;
context.humanChangesTruncated = true;
assert.equal((await session.call("tandem_pull", {})).ok, false, "incomplete summaries are refused");
context.humanChangesTruncated = false;
changed.meshChanged = true;
assert.equal((await session.call("tandem_pull", {})).ok, false, "mesh changes are not imported as poses");
changed.meshChanged = false;
context.humanChanges = [changed, { ...changed, object: "obj_missing" }];
assert.equal((await session.call("tandem_pull", {})).ok, false, "one stale part refuses the whole batch");
assert.equal(obj.offset.x, base.offset.x, "a refused batch leaves valid parts untouched");
context.humanChanges = [changed];
context.mirrorSession = "another-session";
assert.equal((await session.call("tandem_pull", {})).code, "tandem-conflict", "another desktop session is refused with a stable code");
context.mirrorSession = session.bridgeSession;
context.mirrorSeq = 0;
context.conflict = "box";
assert.equal((await session.call("tandem_pull", {})).code, "tandem-conflict", "a reported conflict takes precedence over waiting for a snapshot");
context.conflict = null;
assert.equal((await session.call("tandem_pull", {})).code, "tandem-busy", "an unacknowledged plate snapshot is refused with a stable code");
context.mirrorSeq = session.bridgePlateSeq;
session.inflight = 1;
assert.equal((await session.call("tandem_pull", {})).ok, false, "another in-flight MCP operation is refused");
session.inflight = 0;
await mirror({ test: "drain" });
delete process.env.LIME_MCP_BRIDGE;
delete process.env.LIME_MCP_BRIDGE_TOKEN;
await new Promise<void>((resolve, reject) => server.close((error) => error ? reject(error) : resolve()));
console.log("tandem pull: placement, undo, stale baseline and unsafe inputs");
